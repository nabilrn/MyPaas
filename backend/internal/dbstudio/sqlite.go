type sqliteAdapter struct{}

func openSQLiteDatabase(ctx context.Context, databasePath string) (*sql.DB, error) {
	databasePath = strings.TrimSpace(databasePath)
	if databasePath == "" {
		return nil, fmt.Errorf("%w: SQLite database path is required", errs.ErrValidation)
	}
	conn, err := sql.Open("sqlite", "file:"+databasePath+"?mode=rw&_pragma=foreign_keys(1)&_pragma=busy_timeout(5000)")
	if err != nil {
		return nil, err
	}
	conn.SetMaxOpenConns(1)
	conn.SetMaxIdleConns(1)
	if err := conn.PingContext(ctx); err != nil {
		_ = conn.Close()
		return nil, err
	}
	return conn, nil
}

func (sqliteAdapter) Schemas(context.Context, *sql.DB) ([]Schema, error) {
	return []Schema{{Name: "main"}}, nil
}

func (sqliteAdapter) Tables(ctx context.Context, conn *sql.DB, schema string) ([]Table, error) {
	if err := validateSQLiteSchema(schema); err != nil {
		return nil, err
	}
	rows, err := conn.QueryContext(ctx, `
SELECT 'main', name
FROM sqlite_schema
WHERE type = 'table'
  AND name NOT LIKE 'sqlite_%'
ORDER BY name`)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	return scanTables(rows)
}

func (a sqliteAdapter) Columns(ctx context.Context, conn *sql.DB, schema, table string) ([]Column, error) {
	if err := validateTable(ctx, conn, a, schema, table); err != nil {
		return nil, err
	}
	rows, err := conn.QueryContext(ctx, `
SELECT name, COALESCE(type, ''), "notnull", pk
FROM pragma_table_info(?)
ORDER BY cid`, table)
	if err != nil {
		return nil, err
	}
	defer rows.Close()

	columns := make([]Column, 0)
	for rows.Next() {
		var item Column
		var notNull, primaryPosition int
		if err := rows.Scan(&item.Name, &item.DataType, &notNull, &primaryPosition); err != nil {
			return nil, err
		}
		item.PrimaryKey = primaryPosition > 0
		item.Nullable = !item.PrimaryKey && notNull == 0
		columns = append(columns, item)
	}
	if err := rows.Err(); err != nil {
		return nil, err
	}

	if len(primaryKeyColumns(columns)) == 1 {
		for index := range columns {
			if columns[index].PrimaryKey && strings.EqualFold(strings.TrimSpace(columns[index].DataType), "INTEGER") {
				withoutRowID, err := sqliteTableWithoutRowID(ctx, conn, table)
				if err != nil {
					return nil, err
				}
				columns[index].AutoGenerated = !withoutRowID
			}
		}
	}
	return columns, nil
}

func (a sqliteAdapter) TableDetails(ctx context.Context, conn *sql.DB, schema, table string) (TableDetails, error) {
	columns, err := a.Columns(ctx, conn, schema, table)
	if err != nil {
		return TableDetails{}, err
	}
	foreignKeys, err := sqliteForeignKeys(ctx, conn, table)
	if err != nil {
		return TableDetails{}, err
	}
	indexes, err := sqliteIndexes(ctx, conn, table)
	if err != nil {
		return TableDetails{}, err
	}
	constraints := sqliteConstraints(columns, foreignKeys, indexes)
	return TableDetails{
		Schema: schema, Name: table, Columns: columns,
		ForeignKeys: foreignKeys, Indexes: indexes, Constraints: constraints,
	}, nil
}

func (a sqliteAdapter) Rows(ctx context.Context, conn *sql.DB, query RowQuery) (RowPage, error) {
	columns, err := a.Columns(ctx, conn, query.Schema, query.Table)
	if err != nil {
		return RowPage{}, err
	}
	limit := normalizeLimit(query.Limit)
	offset := normalizeOffset(query.Offset)
	sqlText, args, err := sqliteSelectSQL(query.Table, columns, query, limit, offset)
	if err != nil {
		return RowPage{}, err
	}
	rows, err := conn.QueryContext(ctx, sqlText, args...)
	if err != nil {
		return RowPage{}, err
	}
	defer rows.Close()
	return scanRows(rows, columns, limit, offset)
}

func (a sqliteAdapter) Insert(ctx context.Context, conn *sql.DB, mutation Mutation) error {
	columns, err := a.Columns(ctx, conn, mutation.Schema, mutation.Table)
	if err != nil {
		return err
	}
	sqlText, args, err := sqliteInsertSQL(mutation, columns)
	if err != nil {
		return err
	}
	_, err = conn.ExecContext(ctx, sqlText, args...)
	return err
}

